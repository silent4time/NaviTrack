// Helper to validate IMEI (15 numeric digits, Luhn check)
export function validateIMEI(imei: string): { isValid: boolean; message: string } {
  const cleanImei = imei.trim().replace(/\s+/g, '');
  if (!/^\d{15}$/.test(cleanImei)) {
    return {
      isValid: false,
      message: 'کد IMEI باید دقیقاً ۱۵ رقم عددی باشد.',
    };
  }

  // Luhn algorithm check
  let sum = 0;
  for (let i = 0; i < 15; i++) {
    let digit = parseInt(cleanImei.charAt(i), 10);
    // Double every second digit from the right (even indices in 0-based index from left)
    if (i % 2 === 1) {
      digit *= 2;
      if (digit > 9) digit -= 9;
    }
    sum += digit;
  }

  // If sum % 10 === 0, valid Luhn
  const isLuhn = sum % 10 === 0;
  return {
    isValid: isLuhn,
    message: isLuhn ? 'شناسه IMEI معتبر است.' : 'کد IMEI ساختار رقم کنترل (Luhn) معتبری ندارد. لطفاً ارقام را بازبینی کنید.',
  };
}

// Generate human-friendly license key NVTRK-XXXX-XXXX-XXXX
export function generateLicenseKey(prefix = 'NVTRK'): string {
  const chars = 'ABCDEFGHJKLMNPQRSTUVWXYZ23456789'; // omit ambiguous 0, O, 1, I
  const seg = (len: number) => {
    let s = '';
    for (let i = 0; i < len; i++) {
      s += chars.charAt(Math.floor(Math.random() * chars.length));
    }
    return s;
  };
  return `${prefix}-${seg(4)}-${seg(4)}-${seg(4)}`;
}

// Stored standalone licenses generated by admin or purchased
export interface StoredLicenseRecord {
  key: string;
  planId: string;
  planName: string;
  durationMonths: number;
  createdAt: string;
  isUsed: boolean;
  usedByImei?: string;
  activatedAt?: string;
  notes?: string;
}

// Initial demo licenses for testing & demonstration
const INITIAL_LICENSES: StoredLicenseRecord[] = [];

